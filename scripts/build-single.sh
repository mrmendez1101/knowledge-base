#!/usr/bin/env sh
# Bundles SKILL.md and all its references into dist/knowledge-base.single.md.
# The bundle is for LLMs that cannot load skill folders, such as Kimi, ChatGPT or Gemini in a web
# chat. Paste or attach the bundle together with the project files.
set -eu

repo_root=$(cd "$(dirname "$0")/.." && pwd)
skill_dir="$repo_root/skill/knowledge-base"
out="$repo_root/dist/knowledge-base.single.md"
# Order matches the order in which SKILL.md tells the model to read them.
refs="update-mode.md discovery-hints.md implicit-env.md output-templates.md onboarding-template.md obsidian-graphify.md verification.md"

mkdir -p "$repo_root/dist"
{
  echo '<!-- Generated by scripts/build-single.sh from skill/knowledge-base. Do not edit by hand. -->'
  echo '> Single-file edition: the skill says "read `references/<name>`". Those references are appended'
  echo '> below as `# Reference: references/<name>` sections. Read each one at the step that names it.'
  echo
  # Drop the YAML frontmatter; it is only meaningful to skill loaders.
  awk 'NR==1 && /^---\r?$/ {fm=1; next} fm && /^---\r?$/ {fm=0; next} !fm' "$skill_dir/SKILL.md"
  echo
  for ref in $refs; do
    [ -f "$skill_dir/references/$ref" ] || { echo "Missing reference: $ref" >&2; exit 1; }
    echo '---'
    echo
    echo "# Reference: references/$ref"
    echo
    cat "$skill_dir/references/$ref"
    echo
  done
} > "$out"

echo "Wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
