<#
.SYNOPSIS
  Bundles SKILL.md and all its references into dist/knowledge-base.single.md.

.DESCRIPTION
  The bundle is for LLMs that cannot load skill folders, such as Kimi, ChatGPT or Gemini in a web
  chat. Paste or attach the bundle together with the project files.
#>
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$skillDir = Join-Path $repoRoot 'skill/knowledge-base'
$outDir = Join-Path $repoRoot 'dist'
$outFile = Join-Path $outDir 'knowledge-base.single.md'

# Order matches the order in which SKILL.md tells the model to read them.
$refs = @('update-mode.md', 'discovery-hints.md', 'implicit-env.md', 'output-templates.md',
          'onboarding-template.md', 'obsidian-graphify.md', 'verification.md')

$skill = [IO.File]::ReadAllText((Join-Path $skillDir 'SKILL.md'))
# Drop the YAML frontmatter; it is only meaningful to skill loaders.
$skill = [regex]::Replace($skill, '\A---\r?\n.*?\r?\n---\r?\n', '', 'Singleline')

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<!-- Generated by scripts/build-single.ps1 from skill/knowledge-base. Do not edit by hand. -->')
[void]$sb.AppendLine('> Single-file edition: the skill says "read `references/<name>`". Those references are appended')
[void]$sb.AppendLine('> below as `# Reference: references/<name>` sections. Read each one at the step that names it.')
[void]$sb.AppendLine()
[void]$sb.Append($skill.TrimEnd()).AppendLine().AppendLine()

foreach ($ref in $refs) {
  $path = Join-Path $skillDir "references/$ref"
  if (-not (Test-Path $path)) { throw "Missing reference: $path" }
  [void]$sb.AppendLine('---').AppendLine()
  [void]$sb.AppendLine("# Reference: references/$ref").AppendLine()
  [void]$sb.Append(([IO.File]::ReadAllText($path)).TrimEnd()).AppendLine().AppendLine()
}

New-Item -ItemType Directory -Force $outDir | Out-Null
[IO.File]::WriteAllText($outFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $outFile ($([math]::Round((Get-Item $outFile).Length / 1KB, 1)) KB)"
